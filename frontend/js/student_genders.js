    function normalizeArabicName(name) {
        if (!name) return '';
        return String(name)
            .replace(/[\u064B-\u065F\u0670]/g, '')
            .replace(/[أإآ]/g, 'ا')
            .replace(/ة/g, 'ه')
            .replace(/ى/g, 'ي')
            .trim();
    }

    function getStudentGender(identifier, name, explicitGender) {
        // 1. LocalStorage overrides
        try {
            const stored = JSON.parse(localStorage.getItem('monir_students_gender_overrides') || '{}');
            if (identifier) {
                const cleanId = String(identifier).trim().toUpperCase();
                if (stored[cleanId]) return stored[cleanId];
                const num = cleanId.replace(/\D/g, '');
                if (num && stored[num]) return stored[num];
            }
        } catch(e) {}

        // 2. Direct code / ID lookup
        if (identifier) {
            const cleanId = String(identifier).trim().toUpperCase();
            if (window.STUDENT_GENDER_MAP && window.STUDENT_GENDER_MAP[cleanId]) {
                return window.STUDENT_GENDER_MAP[cleanId];
            }
            const num = cleanId.replace(/\D/g, '');
            if (num) {
                const intNum = String(parseInt(num, 10));
                if (window.STUDENT_GENDER_MAP && window.STUDENT_GENDER_MAP[intNum]) {
                    return window.STUDENT_GENDER_MAP[intNum];
                }
            }
        }

        // 3. Name lookup in verified directory
        if (name) {
            const cleanName = String(name).trim();
            if (window.STUDENT_GENDER_BY_NAME && window.STUDENT_GENDER_BY_NAME[cleanName]) {
                return window.STUDENT_GENDER_BY_NAME[cleanName];
            }
            const norm = normalizeArabicName(cleanName);
            if (window.STUDENT_GENDER_BY_NAME && window.STUDENT_GENDER_BY_NAME[norm]) {
                return window.STUDENT_GENDER_BY_NAME[norm];
            }
        }

        // 4. Explicit gender property passed
        if (explicitGender) {
            const g = String(explicitGender).toLowerCase().trim();
            if (g === 'f' || g === 'female' || g === 'بنت' || g === 'أنثى' || g === 'انثى' || g.includes('female') || g.includes('أنثى') || g.includes('بنت')) return 'f';
            if (g === 'm' || g === 'male' || g === 'ولد' || g === 'ذكر' || g.includes('male') || g.includes('ذكر') || g.includes('ولد')) return 'm';
        }

        // 5. General fallback name heuristic
        if (name) {
            const norm = normalizeArabicName(name);
            const first = norm.split(/\s+/)[0] || '';
            const maleExceptions = ['حمزه', 'اسامه', 'طلحه', 'قتاده', 'عبيده', 'معاويه', 'عكرمه', 'حذيفه', 'عتبه', 'قتيبه', 'سلامه', 'جمعه', 'عطيه', 'عرفه', 'شحاته'];
            if (maleExceptions.includes(first)) return 'm';
            if (first.endsWith('ه') || first.endsWith('اء') || first.endsWith('ي')) {
                return 'f';
            }
        }
        return 'm';
    }


